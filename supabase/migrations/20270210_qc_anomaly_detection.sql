  id               uuid                  PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id           uuid                  NOT NULL REFERENCES public.organizations(org_id) ON DELETE CASCADE,
  metric_key       qca_metric_key        NOT NULL,
  threshold_type   qca_threshold_type    NOT NULL,
  min_value        numeric(18, 6),
  max_value        numeric(18, 6),
  zscore_threshold numeric(6, 3)         DEFAULT 3.0,
  is_active        boolean               NOT NULL DEFAULT TRUE,
  description      text,
  created_by       uuid                  NOT NULL REFERENCES auth.users(id),
  created_at       timestamptz           NOT NULL DEFAULT now(),
  updated_at       timestamptz           NOT NULL DEFAULT now(),

  CONSTRAINT qca_threshold_configs_min_max_check
    CHECK (min_value IS NULL OR max_value IS NULL OR min_value <= max_value),
  CONSTRAINT qca_threshold_configs_zscore_pos
    CHECK (zscore_threshold IS NULL OR zscore_threshold > 0)
);

