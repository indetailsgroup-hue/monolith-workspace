-- ─── Auto-detection trigger ──────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION qca_detect_anomaly()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_threshold    qca_threshold_configs%ROWTYPE;
  v_severity     qca_anomaly_severity;
  v_breach       jsonb;
  v_is_anomaly   boolean;
  v_mean         numeric;
  v_stddev       numeric;
  v_zscore       numeric;
BEGIN
  FOR v_threshold IN
    SELECT *
    FROM   qca_threshold_configs
    WHERE  org_id     = NEW.org_id
      AND  metric_key = NEW.metric_key
      AND  is_active  = TRUE
  LOOP
    v_is_anomaly := FALSE;
    v_breach     := '{}'::jsonb;
    v_zscore     := NULL;

    CASE v_threshold.threshold_type

      WHEN 'MIN' THEN
        IF NEW.value < v_threshold.min_value THEN
          v_is_anomaly := TRUE;
          v_breach := jsonb_build_object(
            'type',            'MIN',
            'min_value',       v_threshold.min_value,
            'measured_value',  NEW.value
          );
        END IF;

      WHEN 'MAX' THEN
        IF NEW.value > v_threshold.max_value THEN
          v_is_anomaly := TRUE;
          v_breach := jsonb_build_object(
            'type',            'MAX',
            'max_value',       v_threshold.max_value,
            'measured_value',  NEW.value
          );
        END IF;

      WHEN 'RANGE' THEN
        IF NEW.value < v_threshold.min_value OR NEW.value > v_threshold.max_value THEN
          v_is_anomaly := TRUE;
          v_breach := jsonb_build_object(
            'type',            'RANGE',
            'min_value',       v_threshold.min_value,
            'max_value',       v_threshold.max_value,
            'measured_value',  NEW.value
          );
        END IF;

      WHEN 'ZSCORE' THEN
        SELECT AVG(m.value), STDDEV_POP(m.value)
        INTO   v_mean, v_stddev
        FROM (
          SELECT value
          FROM   qca_measurements
          WHERE  org_id     = NEW.org_id
            AND  metric_key = NEW.metric_key
            AND  id        != NEW.id
          ORDER BY measured_at DESC
          LIMIT 30
        ) m;

        IF v_stddev IS NOT NULL AND v_stddev > 0 THEN
          v_zscore := ABS((NEW.value - v_mean) / v_stddev);
          IF v_zscore > COALESCE(v_threshold.zscore_threshold, 3.0) THEN
            v_is_anomaly := TRUE;
            v_breach := jsonb_build_object(
              'type',            'ZSCORE',
              'zscore',          v_zscore,
              'mean',            v_mean,
              'stddev',          v_stddev,
              'threshold',       COALESCE(v_threshold.zscore_threshold, 3.0),
              'measured_value',  NEW.value
            );
          END IF;
        END IF;

    END CASE;

    IF v_is_anomaly THEN
      -- Derive severity
      IF v_threshold.threshold_type = 'ZSCORE' AND v_zscore IS NOT NULL THEN
        IF    v_zscore >= 5.0 THEN v_severity := 'CRITICAL';
        ELSIF v_zscore >= 4.0 THEN v_severity := 'HIGH';
        ELSIF v_zscore >= 3.5 THEN v_severity := 'MEDIUM';
        ELSE                       v_severity := 'LOW';
        END IF;
      ELSE
        -- For MIN/MAX/RANGE: derive from % breach relative to threshold span
        DECLARE
          v_span    numeric;
          v_pct_err numeric;
        BEGIN
          v_span := COALESCE(v_threshold.max_value, v_threshold.min_value);
          IF v_span IS NOT NULL AND v_span <> 0 THEN
            v_pct_err := ABS(NEW.value - v_span) / ABS(v_span);
            IF    v_pct_err >= 0.50 THEN v_severity := 'CRITICAL';
            ELSIF v_pct_err >= 0.20 THEN v_severity := 'HIGH';
            ELSIF v_pct_err >= 0.05 THEN v_severity := 'MEDIUM';
            ELSE                         v_severity := 'LOW';
            END IF;
          ELSE
            v_severity := 'MEDIUM';
          END IF;
        END;
      END IF;

      INSERT INTO qca_anomaly_events (
        org_id, metric_key, measurement_id, threshold_id,
        severity, status, measured_value, threshold_breach_detail
      ) VALUES (
        NEW.org_id, NEW.metric_key, NEW.id, v_threshold.id,
        v_severity, 'OPEN', NEW.value, v_breach
      );
    END IF;

  END LOOP;

  RETURN NEW;
END;
$$;

