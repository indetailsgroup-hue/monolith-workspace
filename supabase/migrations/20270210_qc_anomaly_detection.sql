-- ─── Helper: plan gate ───────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION qca_is_enterprise(p_org_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.organizations
    WHERE org_id = p_org_id
      AND plan   = 'ENTERPRISE'
  );
$$;

