-- ─── View: anomaly summary per org + metric ──────────────────────────────────

CREATE OR REPLACE VIEW qca_anomaly_summary_v AS
SELECT
  org_id,
  metric_key,
  COUNT(*)        FILTER (WHERE status = 'OPEN')         AS open_count,
  COUNT(*)        FILTER (WHERE status = 'ACKNOWLEDGED') AS acknowledged_count,
  COUNT(*)        FILTER (WHERE status = 'RESOLVED')     AS resolved_count,
  MAX(created_at) FILTER (WHERE status = 'OPEN')         AS last_open_anomaly_at,
  MAX(created_at)                                        AS last_anomaly_at
FROM  qca_anomaly_events
GROUP BY org_id, metric_key;

